#!/usr/bin/env python3
"""Generate caliptra_top_flat.sv, a flat-port wrapper around caliptra_top.

caliptra_top exposes six SystemVerilog INTERFACE ports (four axi_if modports
plus the VeeR and ABR memory exports).  read_slang refuses to elaborate a
top-level module with an unconnected interface port, and a miter or co-sim
needs real ports anyway, so the campaign drives the chip through this wrapper.

The wrapper's port widths are taken from an RTLIL netlist of caliptra_top
rather than re-parsed from SystemVerilog: the interface members reach the
importer already elaborated (axi_if's AW/DW/IW/UW, el2_mem_if's `pt` struct
and abr_mem_if's macro-generated widths all resolved), so the netlist is the
one place the true geometry is written down.

  usage: gen_wrapper.py <caliptra_top.il> <out.sv>
"""
import re, sys

# chip interface port -> (interface type, modport, instantiation arguments)
IFACES = {
    "s_axi_w_if":        ("axi_if",     "w_sub",         "S_AXI", "(.clk(clk), .rst_n(cptra_rst_b))"),
    "s_axi_r_if":        ("axi_if",     "r_sub",         "S_AXI", "(.clk(clk), .rst_n(cptra_rst_b))"),
    "m_axi_w_if":        ("axi_if",     "w_mgr",         "M_AXI", "(.clk(clk), .rst_n(cptra_rst_b))"),
    "m_axi_r_if":        ("axi_if",     "r_mgr",         "M_AXI", "(.clk(clk), .rst_n(cptra_rst_b))"),
    "el2_mem_export":    ("el2_mem_if", "veer_sram_src", None,    "()"),
    "abr_memory_export": ("abr_mem_if", "req",           None,    "()"),
}
# The read and write halves of one AXI port are two modports of the SAME
# interface instance, so they share one instance in the wrapper.
SHARED = {"s_axi_w_if": "s_axi_i", "s_axi_r_if": "s_axi_i",
          "m_axi_w_if": "m_axi_i", "m_axi_r_if": "m_axi_i",
          "el2_mem_export": "el2_mem_i", "abr_memory_export": "abr_mem_i"}

WIRE = re.compile(
    r"^\s+wire\s+(?:width\s+(\d+)\s+)?(?:offset\s+(-?\d+)\s+)?"
    r"(input|output|inout)\s+\d+\s+\\(\S+)\s*$")


def ports_of(il_path, top):
    """[(width, dir, name)] for `top`, in declaration order."""
    out, inmod = [], False
    with open(il_path, errors="replace") as fh:
        for line in fh:
            if line.startswith("module "):
                inmod = line.strip() == "module \\" + top
                continue
            if not inmod:
                continue
            if line.startswith("end"):
                break
            m = WIRE.match(line.rstrip("\n"))
            if m:
                out.append((int(m.group(1) or 1), m.group(3), m.group(4)))
    return out


def main():
    il, out = sys.argv[1], sys.argv[2]
    all_ports = ports_of(il, "caliptra_top")
    # axi_if's four parameters are not written down anywhere the wrapper can
    # reach, but each one IS the width of a member the netlist already carries:
    # AW=araddr, DW=rdata, IW=arid, UW=aruser.  Read them back per AXI port.
    by_name = {n: w for w, _, n in all_ports}
    axi_params = {}
    for tag, rd in (("S_AXI", "s_axi_r_if"), ("M_AXI", "m_axi_r_if")):
        for sfx, sig in (("AW", "araddr"), ("DW", "rdata"),
                         ("IW", "arid"), ("UW", "aruser")):
            axi_params[f"{tag}_{sfx}"] = by_name.get(f"{rd}.{sig}", 32)
    decls, insts, conns, chip = [], [], [], []
    seen_inst = set()
    for width, direction, name in all_ports:
        base, _, field = name.partition(".")
        rng = "" if width == 1 else f"[{width - 1}:0] "
        if not field or base not in IFACES:
            decls.append(f"  {direction} logic {rng}{name}")
            chip.append(f"    .{name}({name})")
            continue
        iface, modport, params, args = IFACES[base]
        inst = SHARED[base]
        if inst not in seen_inst:
            seen_inst.add(inst)
            pfx = f"#(.AW({params}_AW), .DW({params}_DW), " \
                  f".IW({params}_IW), .UW({params}_UW)) " if params else ""
            insts.append(f"  {iface} {pfx}{inst} {args};")
            chip_conn = True
        flat = f"{base}_{field}"
        decls.append(f"  {direction} logic {rng}{flat}")
        # An `input` of the chip is an input of the wrapper: drive the
        # interface member from it.  An `output` flows the other way.
        if direction == "input":
            conns.append(f"  assign {inst}.{field} = {flat};")
        else:
            conns.append(f"  assign {flat} = {inst}.{field};")
    for base, (iface, modport, _, _) in IFACES.items():
        chip.append(f"    .{base}({SHARED[base]}.{modport})")

    params = "".join(f"  localparam int {k} = {v};\n"
                     for k, v in sorted(axi_params.items()))
    with open(out, "w") as fh:
        fh.write("// GENERATED by scripts/gen_wrapper.py -- do not edit by hand.\n"
                 "// Flat-port wrapper around caliptra_top: each of the chip's six\n"
                 "// interface ports becomes a set of ordinary wrapper ports, so\n"
                 "// read_slang can elaborate the design and a co-sim testbench can\n"
                 "// drive it.  Regenerate with:\n"
                 "//   scripts/gen_wrapper.py work/caliptra_top.il caliptra_top_flat.sv\n"
                 "module caliptra_top_flat (\n")
        fh.write(",\n".join(decls) + "\n);\n")
        fh.write(params)
        fh.write("\n".join(insts) + "\n\n")
        fh.write("  caliptra_top chip (\n" + ",\n".join(chip) + "\n  );\n\n")
        fh.write("\n".join(conns) + "\nendmodule\n")
    print(f"# wrote {out}: {len(decls)} ports, {len(insts)} interface instances")


main()
